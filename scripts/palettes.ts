// Builds the madoromi palettes from the inks' ramps (see src/core/palette.ts) and writes every port
// of them under palettes/ (see src/ports), with the readme and the style guide. Prints each
// flavour's contrast and harmony, and fails if any minimum isn't met.
// Usage: bun run palettes
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { PRECOMPUTED_DIR } from "../src/core/cloudfile";
import { contrast, oklabToOklch } from "../src/core/color";
import { guideMarkdown } from "../src/core/guide";
import { ACCENTS, NEUTRALS, buildFamily, checkFlavour, encodeFamily, harmonyOf } from "../src/core/palette";
import { contrast as contrastOf } from "../src/core/color";
import { SUMMARY_FILE, decodeSummary } from "../src/core/summary";
import { GROUPS, PORTS, portFiles, step, type Files } from "../src/ports";

const OUT = "palettes";
/** Everything under palettes/ that this script writes. */
const GENERATED = ["README.md", "style-guide.md", "madoromi.json", ...new Set(PORTS.map((p) => p.dir).filter((d) => d !== "."))];

const summary = decodeSummary(JSON.parse(readFileSync(join("public", PRECOMPUTED_DIR, SUMMARY_FILE), "utf8")));
if (!summary) throw new Error("the summary is out of date: run `bun run preprocess` first");
const family = buildFamily(summary.views);

// --- Report.
let failed = 0;
for (const f of family) {
  const paper = f.colours.kami.lab;
  console.log(`\n${f.id}  kami ${f.colours.kami.hex}  sumi ${f.colours.sumi.hex}`);
  const line = (key: string) => {
    const c = f.colours[key];
    const [L, C, h] = oklabToOklch(c.lab);
    return `${key.padEnd(9)} ${c.hex}  ${c.ink.padEnd(16)} at L ${c.L.toFixed(2)}  oklch ${L.toFixed(2)} ${C.toFixed(2)} ${h.toFixed(0).padStart(3)}  ${contrast(c.lab, paper).toFixed(1).padStart(4)}:1`;
  };
  const h = harmonyOf(f);
  console.log(
    `  harmony: L** ${h.apparent.mean.toFixed(3)} ± ${h.apparent.sd.toFixed(3)}, glow ${h.glow.toFixed(3)}, chroma ${h.chroma.mean.toFixed(3)} ± ${h.chroma.sd.toFixed(3)}, gamut ${h.gamut.toFixed(2)}; loudest ${h.loudest.key} (glow ${h.loudest.glow.toFixed(3)})`,
  );
  for (const a of ACCENTS) console.log("  " + line(a.key));
  for (const n of NEUTRALS) console.log("  " + line(n.key));
  for (const c of checkFlavour(f).filter((c) => c.value < c.min)) {
    console.log(`  FAIL ${c.what}: ${c.value.toFixed(3)} < ${c.min}`);
    failed++;
  }
}

// --- The readme: what's here and how to install each port.
const example = family.find((f) => f.id === "haru-yoru")!;
const readme = [
  "# madoromi palettes",
  "",
  "Four seasons (haru 春, natsu 夏, aki 秋, fuyu 冬), each by day (hiru 昼, light) and by night (yoru 夜, dark). Every accent is one of Pilot's iroshizuku inks at some dilution, and the neutrals carry the cast of each season's grey ink; `madoromi.json` names the ink behind each colour. Which colour goes where: [style-guide.md](style-guide.md).",
  "",
  "Everything here is generated by `bun run palettes`. The examples use haru-yoru; any flavour works. The commands run from the repository's root.",
  ...GROUPS.flatMap((g) => [
    "",
    `## ${g.name}`,
    ...PORTS.filter((p) => p.group === g.id).flatMap((p) => [
      "",
      `### ${p.name}`,
      "",
      ...p.install.map((s, i) => `${i + 1}. ${step(s, example)}`),
      ...(p.command ? ["", "```sh", step(p.command, example), "```"] : []),
    ]),
  ]),
].join("\n");

const files: Files = { ...portFiles(family), "README.md": readme, "style-guide.md": guideMarkdown(family) };
for (const g of GENERATED) rmSync(join(OUT, g), { recursive: true, force: true });
for (const [path, text] of Object.entries(files)) {
  const to = join(OUT, path);
  if (!existsSync(dirname(to))) mkdirSync(dirname(to), { recursive: true });
  writeFileSync(to, text.endsWith("\n") ? text : text + "\n");
}
console.log(`\nwrote ${Object.keys(files).length} files under ${OUT}/`);

// --- The app's copy: the family itself (so the page needn't build it), and the colours the page
// is painted in before anything else loads, inlined into index.html.
writeFileSync("src/flavours.json", JSON.stringify(encodeFamily(family)));
const paint = Object.fromEntries(
  family.map((f) => {
    const c = (k: string) => f.colours[k].hex;
    const link = ["sora", "ai", "sumi"].find((k) => contrastOf(f.colours[k].lab, f.colours.hyoshi.lab) >= 4.5) ?? "sumi";
    return [f.id, [c("kami"), c("sumi"), c("usuzumi0"), c("kasure0"), c("nijimi0"), c(link), c("fuji")]];
  }),
);
const START = "<!-- madoromi:theme -->";
const END = "<!-- /madoromi:theme -->";
const html = readFileSync("index.html", "utf8");
const script = `${START}
    <script>
      // The chosen flavour's paper and ink, before the page is drawn (see src/theme.tsx).
      (function () {
        var P = ${JSON.stringify(paint)};
        var id;
        try { id = localStorage.getItem("madoromi-flavour"); } catch (e) {}
        if (!P[id]) {
          var m = new Date().getMonth();
          var s = m >= 2 && m <= 4 ? "haru" : m >= 5 && m <= 7 ? "natsu" : m >= 8 && m <= 10 ? "aki" : "fuyu";
          id = s + (matchMedia("(prefers-color-scheme: dark)").matches ? "-yoru" : "-hiru");
        }
        var c = P[id], r = document.documentElement.style, n = ["--paper", "--ink", "--dim", "--faint", "--hair", "--link", "--m-fuji"];
        for (var i = 0; i < n.length; i++) r.setProperty(n[i], c[i]);
        r.setProperty("color-scheme", id.slice(-4) === "yoru" ? "dark" : "light");
        var l = document.createElement("link");
        l.rel = "preload"; l.as = "image"; l.href = "/precomputed/strokes" + (id.slice(-4) === "yoru" ? "-yoru" : "") + ".webp";
        document.head.appendChild(l);
      })();
    </script>
    ${END}`;
const i0 = html.indexOf(START);
const i1 = html.indexOf(END);
if (i0 < 0 || i1 < 0) throw new Error("index.html has no madoromi:theme block");
writeFileSync("index.html", html.slice(0, i0) + script + html.slice(i1 + END.length));
console.log("wrote src/flavours.json and index.html's theme");

// --- The share image: the eight flavours side by side, each its paper with its accents and its
// ladder of neutrals. No text, so it reads in any language.
{
  const W = 1200;
  const H = 630;
  const col = W / family.length;
  const rects = family.flatMap((f, i) => {
    const x = i * col;
    const accents = ACCENTS.map((a, k) => `<rect x="${x + 28}" y="${84 + k * 26}" width="${col - 56}" height="18" rx="9" fill="${f.colours[a.key].hex}"/>`);
    const ladder = ["chitsu", "hyoshi", "nijimi0", "nijimi1", "nijimi2", "kasure0", "kasure1", "kasure2", "usuzumi0", "usuzumi1", "sumi"].map(
      (k, j) => `<rect x="${x + 28 + j * ((col - 56) / 11)}" y="${H - 96}" width="${(col - 56) / 11 + 0.5}" height="34" fill="${f.colours[k].hex}"/>`,
    );
    return [`<rect x="${x}" y="0" width="${col + 1}" height="${H}" fill="${f.colours.kami.hex}"/>`, ...accents, ...ladder];
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">${rects.join("")}</svg>`;
  const { default: sharp } = await import("sharp");
  await sharp(Buffer.from(svg)).png().toFile("public/og.png");
  console.log("wrote public/og.png");
}
if (failed) {
  console.error(`${failed} checks failed`);
  process.exit(1);
}
