const settings = (f: Flavour, s: Style) => ({ foreground: role(f, s.fg), ...(s.style ? { fontStyle: s.style } : {}) });

function theme(f: Flavour) {
  return {
    name: themeName(f),
    type: isDark(f) ? "dark" : "light",
    semanticHighlighting: true,
    colors: workbench(f),
    tokenColors: SCOPES.map(([scope, s]) => ({ scope, settings: settings(f, s) })),
    semanticTokenColors: Object.fromEntries(Object.entries(SEMANTIC).map(([k, s]) => [k, settings(f, s)])),
  };
}

export function vscode(family: Flavour[]): Files {
  const out: Files = {};
  for (const f of family) out[`vscode/themes/${slug(f)}.json`] = JSON.stringify(theme(f), null, 2);
  out["vscode/package.json"] = JSON.stringify(
    {
      name: "madoromi",
      displayName: "madoromi",
      description: `Colour themes made of Pilot iroshizuku inks: ${SEASONS.map((s) => s.id).join(", ")}, each by day and by night.`,
      version: "0.1.0",
      publisher: "madoromi",
      license: "MPL-2.0",
      engines: { vscode: "^1.80.0" },
      categories: ["Themes"],
      contributes: {
        themes: family.map((f) => ({ label: themeName(f), uiTheme: isDark(f) ? "vs-dark" : "vs", path: `./themes/${slug(f)}.json` })),
      },
    },
    null,
    2,
  );
  return out;
}
