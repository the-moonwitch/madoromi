// A Zed theme family with every flavour.
import type { Flavour, Role } from "../core/palette";
import { AUTHOR, alpha, hex, isDark, role, themeName, type Files } from "./common";

type Style = { fg: Role; style?: "italic"; weight?: number };
// An array, as `constructor` would clash with an object's own.
const SYNTAX: [string, Style][] = [
  ["primary", { fg: "text" }],
  ["variable", { fg: "text" }],
  ["variable.special", { fg: "self", style: "italic" }],
  ["comment", { fg: "comment", style: "italic" }],
  ["comment.doc", { fg: "comment", style: "italic" }],
  ["punctuation", { fg: "punctuation" }],
  ["punctuation.bracket", { fg: "punctuation" }],
  ["punctuation.delimiter", { fg: "punctuation" }],
  ["punctuation.special", { fg: "escape" }],
  ["punctuation.list_marker", { fg: "list" }],
  ["keyword", { fg: "keyword" }],
  ["operator", { fg: "operator" }],
  ["string", { fg: "string" }],
  ["string.escape", { fg: "escape" }],
  ["string.regex", { fg: "regexp" }],
  ["string.special", { fg: "escape" }],
  ["string.special.symbol", { fg: "constant" }],
  ["number", { fg: "number" }],
  ["boolean", { fg: "constant" }],
  ["constant", { fg: "constant" }],
  ["enum", { fg: "type" }],
  ["variant", { fg: "enumMember" }],
  ["function", { fg: "function" }],
  ["constructor", { fg: "type" }],
  ["preproc", { fg: "macro" }],
  ["embedded", { fg: "text" }],
  ["attribute", { fg: "attribute" }],
  ["type", { fg: "type" }],
  ["property", { fg: "property" }],
  ["label", { fg: "label" }],
  ["tag", { fg: "tag" }],
  ["title", { fg: "heading", weight: 700 }],
  ["emphasis", { fg: "text", style: "italic" }],
  ["emphasis.strong", { fg: "text", weight: 700 }],
  ["link_text", { fg: "link" }],
  ["link_uri", { fg: "link", style: "italic" }],
  ["text.literal", { fg: "code" }],
  ["hint", { fg: "comment" }],
  ["predictive", { fg: "comment", style: "italic" }],
];

function style(f: Flavour) {
  const c = (k: string) => hex(f, k);
  const r = (k: Role) => role(f, k);
  const accent = r("accent");
  const ansi = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];
  const state = (name: string, k: Role) => ({
    [name]: r(k),
    [`${name}.background`]: alpha(r(k), 0.12),
    [`${name}.border`]: alpha(r(k), 0.5),
  });
  // Every collaborator a cursor colour; the first is the cursor's own.
  const players = (["cursor", "function", "string", "keyword", "type", "tag", "operator", "number"] as Role[]).map((k) => ({
    cursor: r(k),
    background: r(k),
    selection: alpha(r(k), 0.25),
  }));
  return {
    border: c("nijimi0"),
    "border.variant": c("hyoshi"),
    "border.focused": accent,
    "border.selected": accent,
    "border.transparent": alpha(c("kami"), 0),
    "border.disabled": c("nijimi0"),
    "elevated_surface.background": c("hyoshi"),
    "surface.background": c("hyoshi"),
    background: c("chitsu"),
    "element.background": c("hyoshi"),
    "element.hover": c("nijimi0"),
    "element.active": c("nijimi1"),
    "element.selected": c("nijimi0"),
    "element.disabled": c("hyoshi"),
    "drop_target.background": alpha(accent, 0.2),
    "ghost_element.background": alpha(c("kami"), 0),
    "ghost_element.hover": alpha(c("nijimi0"), 0.6),
    "ghost_element.active": c("nijimi1"),
    "ghost_element.selected": c("nijimi0"),
    "ghost_element.disabled": alpha(c("kami"), 0),
    text: c("sumi"),
    "text.muted": c("usuzumi0"),
    "text.placeholder": c("kasure1"),
    "text.disabled": c("kasure0"),
    "text.accent": accent,
    icon: c("usuzumi0"),
    "icon.muted": c("kasure1"),
    "icon.disabled": c("kasure0"),
    "icon.placeholder": c("kasure1"),
    "icon.accent": accent,
    "status_bar.background": c("chitsu"),
    "title_bar.background": c("chitsu"),
    "title_bar.inactive_background": c("chitsu"),
    "toolbar.background": c("kami"),
    "tab_bar.background": c("chitsu"),
    "tab.inactive_background": c("hyoshi"),
    "tab.active_background": c("kami"),
    "search.match_background": alpha(r("match"), 0.3),
    "panel.background": c("hyoshi"),
    "panel.focused_border": accent,
    "pane.focused_border": accent,
    "pane_group.border": c("nijimi0"),
    "scrollbar.thumb.background": alpha(c("nijimi2"), 0.4),
    "scrollbar.thumb.hover_background": alpha(c("nijimi2"), 0.7),
    "scrollbar.thumb.border": alpha(c("kami"), 0),
    "scrollbar.track.background": alpha(c("kami"), 0),
    "scrollbar.track.border": alpha(c("kami"), 0),
    "editor.foreground": c("sumi"),
    "editor.background": c("kami"),
    "editor.gutter.background": c("kami"),
    "editor.subheader.background": c("hyoshi"),
    "editor.active_line.background": alpha(c("nijimi0"), 0.45),
    "editor.highlighted_line.background": alpha(c("nijimi0"), 0.6),
    "editor.line_number": c("nijimi2"),
    "editor.active_line_number": accent,
    "editor.invisible": c("nijimi1"),
    "editor.wrap_guide": c("nijimi0"),
    "editor.active_wrap_guide": c("nijimi1"),
    "editor.indent_guide": c("nijimi0"),
    "editor.indent_guide_active": c("nijimi2"),
    "editor.document_highlight.read_background": alpha(c("nijimi1"), 0.5),
    "editor.document_highlight.write_background": alpha(c("nijimi2"), 0.5),
    "terminal.background": c("kami"),
    "terminal.foreground": c("sumi"),
    "terminal.bright_foreground": c("sumi"),
    "terminal.dim_foreground": c("usuzumi0"),
    ...Object.fromEntries(f.ansi.map((s, i) => [`terminal.ansi.${i < 8 ? "" : "bright_"}${ansi[i % 8]}`, s.hex])),
    "link_text.hover": r("link"),
    ...state("error", "error"),
    ...state("warning", "warning"),
    ...state("info", "info"),
    ...state("hint", "hint"),
    ...state("success", "success"),
    ...state("created", "added"),
    ...state("modified", "modified"),
    ...state("deleted", "deleted"),
    ...state("conflict", "keyword"),
    ...state("renamed", "info"),
    ...state("ignored", "comment"),
    ...state("hidden", "comment"),
    ...state("unreachable", "comment"),
    ...state("predictive", "comment"),
    players,
    syntax: Object.fromEntries(
      SYNTAX.map(([k, s]) => [k, { color: r(s.fg), font_style: s.style ?? null, font_weight: s.weight ?? null }]),
    ),
  };
}

export function zed(family: Flavour[]): Files {
  return {
    "zed/madoromi.json": JSON.stringify(
      {
        $schema: "https://zed.dev/schema/themes/v0.2.0.json",
        name: "madoromi",
        author: AUTHOR,
        themes: family.map((f) => ({ name: themeName(f), appearance: isDark(f) ? "dark" : "light", style: style(f) })),
      },
      null,
      2,
    ),
  };
}
